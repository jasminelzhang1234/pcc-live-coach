"""Entry point: `python -m phase_b` boots uvicorn."""

import uvicorn

from phase_b.config import get_settings


def main() -> None:
    s = get_settings()
    uvicorn.run(
        "phase_b.server:app",
        host=s.host,
        port=s.port,
        log_level=s.log_level,
        reload=False,
    )


if __name__ == "__main__":
    main()